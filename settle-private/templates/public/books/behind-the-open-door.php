      <h3 class="subsec">The Haiti Mission</h3>
      <hr class="rule2">
      <p><span class="folio">21</span>In 1977, VIM again contacted the Open Door Class for Mission assistance &mdash; this time in Haiti. The project was to construct a Church-School building on Ile de La Gonave (a Haitian island 35 miles off the mainland). Funding was solicited from members of Settle. A delegation from the Class approached Marian Lewis and she submitted Forrest as the &ldquo;volunteer.&rdquo; La Gonave is a desolate island whose inhabitants practice Christianity and Voodooism. Until the construction of this Church-School building, structures were of mud and straw. The new building was of cement blocks with a corrugated metal roof. The community was revisited one year later &mdash; teachers were teaching and church attendance was approximately 125. Mission accomplished!</p>

