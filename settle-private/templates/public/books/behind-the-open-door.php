      <h3 class="subsec">Mary Kendall Home</h3>
      <hr class="rule2">
      <p>In 1986, faced with the reality of a project (remodeling for the Boys&rsquo; Home) in need of funding, <span class="folio">16</span>the Mary Kendall Home Board of Directors began seeking ways and means by which to raise essential funds for the purchase of paint and other supplies, and the recruitment of individuals possessed of a special loving and caring philosophy easily converted to Christian outreach. They turned to a group of individuals who, time after time, had established themselves as ones whom other like-minded and caring Christians should follow. They tapped the enormous reservoir of love and talent of Methodist churches within Owensboro and the surrounding area.</p>
      <p>The Board of the Mary Kendall Home had become aware of a need to find a place in the community for some special but unfortunate young men who, for whatever reason, but more often than not, had experienced trouble with the &ldquo;Law.&rdquo; They needed some place where they could live and experience an atmosphere of love and caring; what better place than a Christian setting within the confines of the Mary Kendall Home &mdash; a facility already operating with special goals of creating an environment within which these young men could share their feelings with trained professionals whose desire it was that these individuals turn their lives around and become responsible community citizens.</p>
      <p>But the Board needed help! Once again, the Open Door Class came to the rescue. They took their paint brushes, scrapers, ladders, etc., to the Mary Kendall Home to help in converting an old, dingy, gloomy section into a unit offering a refreshing appeal to those young people who would make it their home for a period of time during which they fought to overcome a past fraught with &ldquo;troubles.&rdquo;</p>
      <p>The Class worked off and on for approximately a week in cleaning, scraping and painting those old rooms, readying them to receive those special young-<span class="folio">17</span>sters. The Open Door Class of Settle Memorial takes comfort in the knowledge that they had another opportunity to help &ldquo;Others&rdquo; along the way to a better life.</p>
      <p>With the Open Door Class, the special caring didn&rsquo;t stop there. The Class has sponsored one &ldquo;hole&rdquo; in a golfing event for the benefit of the Mary Kendall Home and the sponsor of &ldquo;Friends of the Children.&rdquo;</p>
      <p>As in all such instances, there are a special few who take charge and lead and thus is the case with this special Class of Christian Servants. All, however, have contributed in their own special way and it is therefore not essential to attempt to identify only a few &mdash; for all reflect that special care for &ldquo;Others.&rdquo;</p>

