      <div class="anecdote">
        <p class="atitle">Painting the Caretaker&rsquo;s House</p>
        <p>The day prior to this incident, Ed Barress, <span class="folio">24</span>Bernard Duckwall, Clarence Reynolds, Bernard Miller and George Willis had removed old carpeting and generally cleaned and repaired the house and had it in condition for painting. Jim Shrewsberry and Jim Weakley had also been there and repaired the electrical service. Due to previous plans, Miller and Willis were the only ones that could return the next day to start the painting.</p>
        <p>Miller and Willis, along with several buckets of paint, brushes, etc., arrived at Camp Loucon and immediately began a discussion of procedures whereby they could rapidly finish the job at hand. Miller chose to paint the ceilings and walls with a roller. They began by attempting to pour paint from a five-gallon bucket into a paint tray. This was an un-satisfactory situation.</p>
        <p>It was soon discovered that Miller had never used a roller before as he did not evenly spread the paint on the roller prior to applying it to the ceiling. The roller, full on one side, was applied to the ceiling. The roller didn&rsquo;t turn, but slid across the ceiling dumping large globs of paint on the floor. Miller insisted that he would soon &ldquo;get the hang of it.&rdquo;</p>
        <p>Willis, foolishly, began to apply primer to the woodwork in the same room. Miller&rsquo;s roller was spraying paint everywhere. His glasses were covered with paint and the woodwork was wet with ceiling white.</p>
        <p>An argument resulted and it was decided that Miller would start the ceiling in another room. He picked up his five-gallon paint bucket, step ladder, trays, rags and left. Peace and harmony prevailed until Willis heard a loud thud in the room where Miller was displaying his artistic talents. Willis feared the worse, as Mrs. Miller had absolutely forbidden Miller&rsquo;s use of a ladder for fear he would fall. By the time Willis was able to start to the room, he looked in the hallway and there stood Miller &mdash; clutching the five-gallon can of <span class="folio">25</span>paint to his chest. (The paint can was partially empty).</p>
        <p>Paint covered him from head to toe. Paint was running from his pants and puddling on the floor. Willis took him out the back door toward the woods and had him remove his clothes so they could wash off the water-based paint. When Willis returned with the first bucket of water and looked out the door, there was Miller in his shorts, covered with white paint, looking like an old Indian coming out of the woods!</p>
        <p>Willis finally got him clean and allowed him back inside after promising that we would not tell Mrs. Miller. Yes, he had extra clothes.</p>
      </div>

      <div class="stars">* * * * * * * * * * * * *</div>

      <div class="anecdote">
        <p class="atitle">Shrewsberry and the Goat</p>
        <p>While working on the caretaker&rsquo;s house at Camp Loucon, Jim Shrewsberry became friendly with a little goat. (Jim is the kind of person that gets friendly with weird things and weird people.) Jim would talk to the goat as you would a child. Jim would be working on the roof and the goat would climb upon the roof of a dog house and try to get to Jim, all the time going &ldquo;Bah-Bah-Bah.&rdquo; Jim would look at the goat and call him a few choice words and go on about his work.</p>
        <p>On a return trip a week or two later, the silly goat heard Jim&rsquo;s voice and came running toward him. Again going, &ldquo;Bah-Bah-Bah.&rdquo; Apparently, Shrewsberry and the goat had a &ldquo;verbal&rdquo; understanding.</p>
      </div>

      <div class="stars">* * * * * * * * * * * * *</div>

      <div class="anecdote">
        <p class="atitle"><span class="folio">26</span>Camp Loucon Nature Museum</p>
        <p>During the time that Dale Brady was Loucon&rsquo;s camp manager and director of activities, plans were made to improve the physical arrangement and condition of the camp. Bernard Miller, representing our area on the camp board, agreed that he, with the help of the Open Door Class and other members of our Church, would do as much as possible to help make these dreams a reality.</p>
        <p>About this time, Dale and Connie, his wife, decided that it would be good to have a building that could be used as a nature museum. All agreed, and plans were started. One cabin that was located away from all others and closer to the area selected for the museum was picked for relocation.</p>
        <p>The cabin had to be moved about one hundred yards if moved in a straight and direct line, and that was the route selected by Miller, our &ldquo;Boss.&rdquo; This line, however, was over rather rough terrain. Almost everyone thought it would be better to take a longer but smoother direction. But, the man with the whip said we should take the straighter line.</p>
        <p>Preparations were made and the cabin was put down on skids that had been used to move other cabins. A tractor, for pulling power, was moved into place and connected.</p>
        <p>Finally, the order was given and the cabin began to move more smoothly than most had predicted. It moved so well that, I think, most of us thought that maybe Miller was right after all. Everyone watched with fingers crossed and breath held until a spot about halfway was reached.</p>
        <p>There in the path of the cabin was a bump, and as the load passed over it, we heard a sudden crunching noise, as if an explosion had been set. And then, the <span class="folio">27</span>entire cabin settled slowly and quietly into a cloud of dust and splinters. The nature museum had suddenly become just a sad memory of what it might have been.</p>
        <p>As usual, Miller just smiled and shrugged and we all agreed that it might not have been such a good idea after all. It wasn&rsquo;t a very good cabin anyhow.</p>
        <p>In the end it didn&rsquo;t turn out too badly. Since the nature museum sounded like such a good thing, it was decided that a new and better house should be built. When it was finished, the Brady&rsquo;s liked it so much that they rededicated the cabin to be used as camp headquarters and main office, leaving the camp still without the nature museum.</p>
      </div>

      <div class="stars">* * * * * * * * * * * * *</div>

      <div class="anecdote">
        <p>Our class constructed a bath house upon a concrete slab laid by others. C. C. Mitchell and Bruce Sayre were painting in the rest room area. It was a light green paint. Mitchell stepped back to admire his work and stepped into the paint bucket. He withdrew his foot and walked to the door, leaving one green footprint at each step as he proceeded along the way. To this day, Mitchell says Sayre stepped in the bucket. Mitchell&rsquo;s wife, Eunice, however, has verified that Mitchell was indeed the culprit.</p>
      </div>

