      <h3 class="subsec">Kirk Memorial Church</h3>
      <hr class="rule2">
      <p>Dr. Charles (Rusty) Kirk donated land to build the Kirk Memorial Church. Guy Harris assisted with the clearing and grading of the lot. Our class contributed approximately $3,000.00 over a period of one year to its construction. Later, the class membership accepted its portion of a challenge to assist Kirk Memorial to liquidate its indebtedness by pledging $11,300.00. Through its resourceful members, their individual pledges and various class projects, the Class proudly met the pledge.</p>
      <p>The Kirk Memorial plaque states: &ldquo;Charles T. Kirk, May 10, 1919 &mdash; September 7, 1960.&rdquo; The Church was erected in 1961.</p>

