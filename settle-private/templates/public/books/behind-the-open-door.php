      <h3 class="subsec">Habitat for Humanity</h3>
      <hr class="rule2">
      <p>Settle Memorial has been extremely active in the <span class="folio">18</span>Habitat program, providing substantial amounts of financial support and countless hours donated by volunteer workers. Our first endeavor into the program was in the summer of 1991 when Settle provided all the money and many volunteers to erect the house at 520 Walnut Street. A construction video was made by Roy Smith.</p>
      <p>One Open Door member, Jim Weakley, was the driving force in getting Settle involved in Habitat. After learning that a Habitat chapter was already established in Owensboro, he contacted Dr. Thurmond and this led to our involvement.</p>
      <p>After the Walnut Street house was completed, plans got underway to start another at 516 Maple Street. Jim Weakley was the project manager on this house and he, along with other Open Door and Settle Members, provided all the volunteer labor to complete this house.</p>
      <p>Open Door Members have also provided countless hours of voluntary help on other houses built by Habitat. These include a house on Orchard Street, one on Nassau Avenue, one on West 9th Street and others. Clarence Reynolds was project manager on two of these.</p>
      <p>Involvement in Habitat for Humanity continues. Open Door Members Jim Weakley, Jim Shrewsberry and Ed Barrass are currently serving on the local Habitat Chapter&rsquo;s Board of Directors.</p>

