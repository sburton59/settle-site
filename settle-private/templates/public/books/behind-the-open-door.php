      <h2 class="sec">The Class<span class="folio">1</span><span class="sub">What Kind of Class Is This?</span></h2>
      <hr class="rule2">

      <p class="lead">Well now, as some wise man must surely have once said, &ldquo;That is a mighty interesting question!&rdquo; To give you some feeling for the Class, when this question was asked of the Class itself, these answers were thrown out &mdash; fun in religion, give and take, open-minded, generous, talented, sharing and &ldquo;none of these,&rdquo; at which point, they were all thrown out again. This question falls into the same category as do the questions, &ldquo;When did you stop beating your wife?&rdquo; and &ldquo;Which came first, the chicken or the egg?&rdquo; There is really no good and consistent way to answer the question, since it significantly depends upon the person to whom you are talking &mdash; the preacher, your wife, or a prospective new member, as examples. You can imagine the wide variation this might produce. It may help you to know that the origin of this Class resides in a group of &ldquo;The Big War&rdquo; veterans, who started it on the premise that we are not taking any more orders &mdash; we are not queuing up again &mdash; we&rsquo;ll smoke if we want to &mdash; we will always have coffee available &mdash; the teacher stops at 10:30 A.M., no excuses &mdash; wives go to some other class &mdash; an occasional joke is acceptable &mdash; and this list could go on and on.</p>

      <p>Now to be a little more specific (but not very revealing), this original group has survived the last forty-five or fifty years in reasonably good shape. The age of the &ldquo;founders&rdquo; is probably from about sixty-five to seventy-five, not that any of them look it or act it. A few interlopers have joined along the way &mdash; several <span class="folio">2</span>younger and even a few older. You can&rsquo;t really tell them from the originals, however, since they have been indoctrinated so thoroughly. Everyone tells the same jokes and stories over and over. Rather comforting when you think of it, because just like a daytime soap opera, if you miss a few episodes, you can pick up right where you left off.</p>

      <p>Surely you will have already noticed that this definition is wandering a bit, much like the whole book is. But then this is the way our lessons (no reflection on the teacher) and conversations in class proceed. We may start with the Good Samaritan and end up with the Bad Democrat/Republican or the Prodigal Son and end with a discussion of the prodigal Social Security system. Are you beginning to get the idea? There have even been times when the prepared lesson was never granted an opening to be delivered. Can you imagine such audacity!</p>

      <p>Members come and go, but, unless called to the Great Class in the sky, they eventually return &mdash; some regularly, some irregularly. Our age engenders those absences which result from retirement leaves, medical leaves, and then, more and more, just simply the fact that we forgot it was Sunday. The Class is in many ways a social club, a men&rsquo;s club, a stag event, a break with the normal routine of life &mdash; a really bright spot in our religious regimen. Lest you are left with the impression that the Class has no religious feelings, rest assured that they do. The centerpiece for these delightful meetings is always, basically, a serious study of the word of God and the teachings of Jesus &mdash; it is just that the Class feels you don&rsquo;t have to appear to be more than you are to be a good Christian and have a little fun along with it.</p>

      <p class="sig">&mdash; William Turner</p>
    </section>

