      <h2 class="sec">In the Beginning<span class="folio">3</span></h2>
      <hr class="rule2">

      <p class="lead">The Open Door Sunday School Class, as it now exists, began in May of 1946 as the &ldquo;Joe Callender&rdquo; Class; taking its name from its first teacher. The Joe Callender Class developed after World War II as the result of a division of the &ldquo;Young People&rsquo;s&rdquo; Class. After the War, the men of the class &mdash; for whatever reason &mdash; broke away from the Young People&rsquo;s Class and formed a Sunday School class of their own, and the women of the Young People&rsquo;s class remained.</p>

      <p>At its inception, the Joe Callender Class began meeting in the Educational Building and afterwards was moved across Fourth Street to the Nunnelly House, the Arnold House, and later to the Haynes House. From the Haynes House, the class was moved to the Educational Building, third floor.</p>

      <p>The Joe Callender Class was still meeting on the third floor of the Educational Building when, in 1962, the members decided to change the name of the class to one which they considered more appropriate for their membership &mdash; &ldquo;The Open Door Class.&rdquo;</p>

      <p>The Open Door Class continued to meet in its room on the third floor of the Educational Building until the renovation program for this structure began in 1973. At that time, the Open Door Class and the Sam Miller Class were asked to consolidate on a temporary basis in order that the Church would be able to adequately handle all Sunday School classes during the renovation period. Thus, the Open Door Class was again moved; this time to the Club Room in the basement<span class="folio">4</span> of the Church building &mdash; this being the regular meeting place for the Sam Miller Bible Class.</p>

      <p>Shortly thereafter, in a further attempt to relieve the cramped circumstances resulting from the evacuation of the Educational Building for construction crews, it became necessary that this consolidated class be moved to the second floor of the Citizens State Bank building, immediately north of the Church.</p>

      <p>The Open Door and the Sam Miller Classes met in this consolidated fashion for approximately a year and a half before moving back to the Church property. The Sam Miller Bible Class returned to its old quarters in the Club Room, and the Open Door Class moved to the second floor of the Educational Building where it continues to meet at this time.</p>

