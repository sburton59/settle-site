      <div class="anecdote">
        <p>Miller installed a long-needed hearing aid. Lewis brought a small radio to Camp Loucon, without Miller&rsquo;s knowledge, to play at the proper time during a cabin <span class="folio">28</span>renovation. The radio was placed under a wood pile and ignored by the workers. Miller began making remarks about hearing music. All others disputed his remarks.</p>
        <p>Finally, Reynolds explained the possibility that the hearing aid was receiving a radio transmission. The hearing aid was removed coinciding with the radio being turned off. For some time the hearing aid was put in and the radio turned on, then out and off, in and on, and so on. We never heard what Miller told his physician.</p>
