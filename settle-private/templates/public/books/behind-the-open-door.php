      <h3 class="subsec">The Milk Fund</h3>
      <hr class="rule2">
      <p>John Ruth, Class member and co-owner of the Chatterbox Restaurant on Third Street in Owensboro, noticed an elderly woman searching through the gar-<span class="folio">14</span>bage cans &mdash; almost every evening. He followed her to a run-down house on Lewis Street.</p>
      <p>Through a window, he observed the woman feed five small children with the garbage. Ruth also observed an open fireplace for heating and cooking, no furniture and rags on the floor for sleeping.</p>
      <p>He related this to the Class and the MILK FUND was initiated. For many years thereafter, the Class provided daily milk delivery, weekly food, clothing, etc., for the family.</p>
      <p>The MILK FUND continues to this day for various community benevolences.</p>

