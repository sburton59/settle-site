      <h3 class="subsec">The Red Bird Mission</h3>
      <hr class="rule2">
      <p>During the summer of 1991, Settle Memorial sponsored a work detail to the Red Bird Mission in Eastern Kentucky. The purpose of this week-long work detail was to install approximately two thousand feet of two-inch underground water line. This new line was needed to upgrade the Mission&rsquo;s water system.</p>
      <p><span class="folio">15</span>Included in this group were three adults and four high school age boys. The adults were Youth Director, Mark Stevens, and Open Door members, Jim Weakley and Jim Shrewsberry. The youth were Brad Blakeman, Damon Kolok, Greg Troutman, and Matt Shrewsberry.</p>
      <p>Because of the terrain at the Red Bird, the job proved to be very difficult. The water line had to cross a creek, go under a paved road, go through an extremely muddy area and down a long hill that was too steep for our ditch digger. The entire ditch line was extremely rocky and hard to dig. Much of it had to be dug by hand.</p>
      <p>The job was to have taken the entire week, but everyone worked very hard so we were ready to leave for home Thursday at noon. All were glad to leave. This turned out to be a &ldquo;not so pleasant experience.&rdquo;</p>

