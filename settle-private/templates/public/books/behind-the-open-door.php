      <h2 class="sec">Class Picnics<span class="folio">29</span></h2>
      <hr class="rule2">

      <p class="lead">In the early 1950&rsquo;s our Class held a supper for members and prospective members in the Flame Room of the Western Kentucky Gas Company building. The meal was prepared and catered by John Ruth of the Chatterbox Restaurant. Other dinners followed and in the early 1960&rsquo;s we held a picnic at B. J. Foster&rsquo;s farm.</p>
      <p>For the first time, the ladies were invited. The attendance was approximately ninety, including our wives. Al Kirkland was the instigator of having the wives attend this and all future Class picnics and dinners.</p>
      <p>Thereafter, about five dinners were held in the Club Room. Grilling of steaks was done in the alley behind the Boy Scout room. Wyndall Smith then invited us to hold our picnics at his farm in the Thruston area which we did for several years until his death.</p>
      <p>One picnic was held at the Field House in Thruston. And one was held at Ralph Thomas&rsquo; cabin on Rough River.</p>
      <p>In later years we held our picnics at the home of Piny Smith. For two years (1991 and 1992) the picnic was held at the home of Forrest and Marian Lewis. Currently the picnic is held at the Green River Electric Corporation picnic grounds. Attendance has always been great.</p>

